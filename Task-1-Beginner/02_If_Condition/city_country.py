city = input("Enter city: ")
country = input("Enter country: ")

if city == "Hyderabad" and country == "India":
    print("You are in Hyderabad, India")
elif city == "Delhi" and country == "India":
    print("You are in Delhi, India")
elif city == "Mumbai" and country == "India":
    print("You are in Mumbai, India")
else:
    print("City and country not found")